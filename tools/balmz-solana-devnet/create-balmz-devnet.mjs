#!/usr/bin/env node
/**
 * BALMZ Devnet mint workflow.
 * No transaction is sent unless --execute-devnet is passed and the exact
 * confirmation phrase is typed interactively. RPC is pinned to Devnet.
 * Keypairs are stored only under ignored .local/ and are never printed.
 * A retry will not mint the initial supply twice.
 */
import { access, mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import readline from "node:readline/promises";
import { stdin as input, stdout as output } from "node:process";
import { Connection, Keypair, LAMPORTS_PER_SOL, PublicKey, clusterApiUrl } from "@solana/web3.js";
import {
  TOKEN_PROGRAM_ID, createMint, getAccount, getAssociatedTokenAddress,
  getMint, getOrCreateAssociatedTokenAccount, mintTo,
} from "@solana/spl-token";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const LOCAL_DIR = path.join(HERE, ".local");
const PAYER_PATH = path.join(LOCAL_DIR, "payer-keypair.json");
const MINT_PATH = path.join(LOCAL_DIR, "mint-keypair.json");
const RPC_URL = clusterApiUrl("devnet");
const TOKEN_SYMBOL = "BALMZ";
const DECIMALS = 9;
const INITIAL_SUPPLY = 1_000_000_000n;
const RAW_SUPPLY = INITIAL_SUPPLY * (10n ** BigInt(DECIMALS));
const CONFIRMATION = "CREATE BALMZ DEVNET TOKEN";

function has(flag) { return process.argv.includes(flag); }
function option(name) {
  const index = process.argv.indexOf(name);
  return index >= 0 ? process.argv[index + 1] : undefined;
}
async function exists(file) {
  try { await access(file); return true; } catch { return false; }
}
async function saveKeypair(file, keypair) {
  await writeFile(file, JSON.stringify(Array.from(keypair.secretKey)) + "\n", { mode: 0o600, flag: "wx" });
}
async function loadKeypair(file) {
  const bytes = JSON.parse(await readFile(file, "utf8"));
  if (!Array.isArray(bytes) || bytes.length !== 64 || bytes.some(n => !Number.isInteger(n) || n < 0 || n > 255)) {
    throw new Error("Local keypair file is malformed: " + path.basename(file));
  }
  return Keypair.fromSecretKey(Uint8Array.from(bytes));
}
async function prepareKeypairs() {
  if (await exists(PAYER_PATH) || await exists(MINT_PATH)) {
    throw new Error("A local keypair already exists. Refusing to overwrite it. Inspect .local/ locally.");
  }
  await mkdir(LOCAL_DIR, { recursive: true, mode: 0o700 });
  const payer = Keypair.generate();
  const mint = Keypair.generate();
  await saveKeypair(PAYER_PATH, payer);
  await saveKeypair(MINT_PATH, mint);
  console.log("Created local-only Devnet keypairs. No network request or transaction was made.");
  console.log("Payer public address (safe to share with a Devnet faucet):", payer.publicKey.toBase58());
  console.log("Candidate mint public key (NOT a live token yet):", mint.publicKey.toBase58());
  console.log("Secret key files are in .local/ and excluded by this folder's .gitignore.");
  console.log("Never upload, paste, or send either keypair file.");
}
async function main() {
  if (has("--prepare-keypairs")) { await prepareKeypairs(); return; }

  const recipientText = option("--recipient");
  if (!has("--execute-devnet")) {
    console.log("DRY RUN — no transaction will be sent.");
    console.log("Network: Solana Devnet only");
    console.log("Token: BALMZ (classic SPL Token; name/symbol metadata is a separate step)");
    console.log("Initial supply:", INITIAL_SUPPLY.toString());
    console.log("Decimals:", DECIMALS);
    console.log("Raw base units:", RAW_SUPPLY.toString());
    console.log("Recipient:", recipientText || "(provide a Phantom public address with --recipient)");
    console.log("Prepare local keypairs with npm run prepare, then fund the payer public address using the official Solana Devnet faucet.");
    console.log("No keypair was generated by this dry run.");
    console.log("Actual creation requires --execute-devnet and typing: " + CONFIRMATION);
    return;
  }
  if (!recipientText) throw new Error("Missing --recipient <PHANTOM_DEVNET_PUBLIC_ADDRESS>.");
  const recipient = new PublicKey(recipientText);
  if (recipient.toBase58() !== recipientText.trim()) throw new Error("Recipient must be a canonical base58 Solana public address.");
  if (!(await exists(PAYER_PATH)) || !(await exists(MINT_PATH))) {
    throw new Error("Local keypairs are missing. Run npm run prepare first; this does not send transactions.");
  }
  const payer = await loadKeypair(PAYER_PATH);
  const mintKeypair = await loadKeypair(MINT_PATH);
  const rl = readline.createInterface({ input, output });
  try {
    const answer = await rl.question("This submits token-creation transactions to SOLANA DEVNET only. Type " + CONFIRMATION + " to continue: ");
    if (answer.trim() !== CONFIRMATION) {
      console.log("Cancelled. No transaction was sent.");
      return;
    }
  } finally { rl.close(); }

  const connection = new Connection(RPC_URL, "confirmed");
  const balance = await connection.getBalance(payer.publicKey, "confirmed");
  console.log("Devnet payer:", payer.publicKey.toBase58());
  console.log("Devnet payer balance:", (balance / LAMPORTS_PER_SOL).toFixed(6), "SOL");
  if (balance < 0.05 * LAMPORTS_PER_SOL) {
    throw new Error("Payer has less than 0.05 Devnet SOL. Use the official Devnet faucet, then rerun. No token transaction was sent.");
  }

  const mintAddress = mintKeypair.publicKey;
  const existingMintAccount = await connection.getAccountInfo(mintAddress, "confirmed");
  let mint;
  if (!existingMintAccount) {
    console.log("Creating the SPL mint on Devnet…");
    await createMint(connection, payer, payer.publicKey, null, DECIMALS, mintKeypair, { commitment: "confirmed" }, TOKEN_PROGRAM_ID);
    mint = await getMint(connection, mintAddress, "confirmed", TOKEN_PROGRAM_ID);
  } else {
    mint = await getMint(connection, mintAddress, "confirmed", TOKEN_PROGRAM_ID);
    if (mint.decimals !== DECIMALS) throw new Error("Existing mint has a different decimals setting; refusing to modify it.");
    if (!mint.mintAuthority?.equals(payer.publicKey)) throw new Error("Existing mint authority does not match the local payer; refusing to mint.");
    if (mint.freezeAuthority !== null) throw new Error("Existing mint has a freeze authority; refusing to continue automatically.");
    console.log("Found the existing Devnet mint; continuing without recreating it.");
  }

  const ataAddress = await getAssociatedTokenAddress(mintAddress, recipient, false, TOKEN_PROGRAM_ID);
  let tokenAccount;
  try {
    tokenAccount = await getAccount(connection, ataAddress, "confirmed", TOKEN_PROGRAM_ID);
  } catch {
    console.log("Creating the recipient's associated token account on Devnet…");
    tokenAccount = await getOrCreateAssociatedTokenAccount(
      connection, payer, mintAddress, recipient, false, "confirmed", undefined, TOKEN_PROGRAM_ID
    );
  }

  mint = await getMint(connection, mintAddress, "confirmed", TOKEN_PROGRAM_ID);
  if (mint.supply === 0n) {
    console.log("Minting the initial supply to the requested public address…");
    await mintTo(connection, payer, mintAddress, tokenAccount.address, payer, RAW_SUPPLY, [], { commitment: "confirmed" }, TOKEN_PROGRAM_ID);
  } else if (mint.supply !== RAW_SUPPLY) {
    throw new Error("Mint already has a nonzero supply different from the configured initial supply. Refusing to mint more.");
  } else {
    const refreshedTokenAccount = await getAccount(connection, tokenAccount.address, "confirmed", TOKEN_PROGRAM_ID);
    if (refreshedTokenAccount.amount !== RAW_SUPPLY) {
      throw new Error("Supply is already minted but the recipient does not hold the full supply. Refusing to mint twice.");
    }
    console.log("The exact initial supply is already minted to this recipient; no additional tokens minted.");
  }

  const finalMint = await getMint(connection, mintAddress, "confirmed", TOKEN_PROGRAM_ID);
  console.log("\nDevnet token mint created/verified.");
  console.log("Network: Solana Devnet");
  console.log("Mint address:", mintAddress.toBase58());
  console.log("Recipient:", recipient.toBase58());
  console.log("Supply:", INITIAL_SUPPLY.toString(), TOKEN_SYMBOL);
  console.log("Decimals:", DECIMALS);
  console.log("Mint authority:", finalMint.mintAuthority?.toBase58() || "revoked");
  console.log("Explorer:", "https://explorer.solana.com/address/" + mintAddress.toBase58() + "?cluster=devnet");
  console.log("Mint authority remains with the local payer keypair. Never lose it or publish it.");
  console.log("This classic SPL mint does not yet have Metaplex name/symbol/logo metadata.");
}
main().catch(error => {
  console.error("BALMZ Devnet workflow stopped:", error?.message || "Unknown error");
  process.exitCode = 1;
});
